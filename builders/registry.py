def modules():
    """All (project, file, builder module, args) entries."""
    return [(p, f, s, a) for p, items in PROJECTS.items() for f, s, a in items]


def project_of(file):
    """The project of the registered module file `file`."""
    for p, items in PROJECTS.items():
        for f, _, _ in items:
            if f == file:
                return p
    raise KeyError(file)
